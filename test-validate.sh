# ── 跑一次测试 ──
run_test() {
  local name="$1" expected="$2" title="$3" report="$4" outfile="$5"; shift 5

  set +e
  local output; output=$(bash "$VALIDATOR" "$report" 2>&1)
  local actual=$?
  set -e

  local exit_ok=true
  [ "$expected" = "pass" ] && [ "$actual" -ne 0 ] && exit_ok=false
  [ "$expected" = "fail" ] && [ "$actual" -eq 0 ] && exit_ok=false

  local pat_ok=true
  for p in "$@"; do
    if ! echo "$output" | grep -qE "$p"; then pat_ok=false; fi
  done

  if $exit_ok && $pat_ok; then
    echo "  ✅ $title"
    PASSED=$((PASSED + 1))
  else
    echo "  ❌ $title ($name)"
    echo "     期望: $expected | 实际: $actual"
    $pat_ok || echo "     未匹配: $*"
    echo "$output" | sed 's/^/       /'
    FAILED=$((FAILED + 1))
  fi
}

echo "🧪 validate-report.sh 回归测试（v3.2 适配）"
